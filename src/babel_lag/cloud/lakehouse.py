"""The `full` lakehouse on Databricks Free Edition (ADR-005, ADR-008).

1. Upload new sanitized landing batches to the UC volume `babel_landing.live` (never rewritten),
   and the compact slice tables (page creations, sitelinks, pageviews) to `babel_landing.slice`.
2. Run the Lakeflow pipeline `babel-lake` (deployed by the asset bundle, or upserted here):
   Auto Loader bronze with expectations, then silver and gold materialized views whose SQL is the
   core SQL (`rollup/sql`) rendered for Spark: the same logic as the DuckDB path.
3. Unity Catalog comments and tags from config/datasets.yml.

Personal data never reaches Databricks: batches are sanitized before they are written locally.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pyarrow.parquet as pq

from babel_lag import __version__
from babel_lag.lake import delta
from babel_lag.lineage.graph import datasets
from babel_lag.paths import DATA, LANDING, ROOT
from babel_lag.rollup import engine
from babel_lag.telemetry.runlog import Stage

PIPELINE = "babel-lake"
SCHEMA = "babel_gold"
SQL_FILE = ROOT / "src/babel_lag/cloud/lakeflow/babel_lake.sql"
WS_PATH = "/Workspace/Shared/babel-lag/babel_lake.sql"
LIVE_VOL = "/Volumes/workspace/babel_landing/live"
SLICE_VOL = "/Volumes/workspace/babel_landing/slice"
SLICE_TABLES = ("silver_page_creations", "silver_sitelinks", "silver_pageviews_daily")
ALL_TABLES = ("gold_language_lag_all", "gold_language_demand_all")
STATE = DATA / "state" / "uploaded.json"

BRONZE = """\
-- Bronze: sanitized EventStreams micro-batches from the landing volume (Auto Loader).
CREATE OR REFRESH STREAMING TABLE bronze_live_events (
  CONSTRAINT has_event_id EXPECT (event_id IS NOT NULL) ON VIOLATION DROP ROW,
  CONSTRAINT has_event_time EXPECT (event_dt IS NOT NULL) ON VIOLATION DROP ROW,
  CONSTRAINT has_wiki EXPECT (wiki IS NOT NULL) ON VIOLATION DROP ROW,
  CONSTRAINT known_stream EXPECT (stream IN ('mediawiki.recentchange',
    'mediawiki.revision-create', 'mediawiki.page-create'))
)
COMMENT '{comment}'
TBLPROPERTIES ('quality' = 'bronze', 'contains_pii' = 'false')
AS SELECT
  meta.id AS event_id,
  CAST(meta.dt AS TIMESTAMP) AS event_dt,
  meta.stream AS stream,
  coalesce(wiki, database) AS wiki,
  CASE WHEN meta.stream = 'mediawiki.recentchange' THEN type
       ELSE element_at(split(meta.stream, '[.]'), -1) END AS event_type,
  CAST(coalesce(namespace, page_namespace) AS INT) AS namespace,
  page_id,
  coalesce(title, page_title) AS page_title,
  rev_id,
  bot AS is_bot,
  page_is_redirect AS is_redirect,
  coalesce(rev_len, length_new) AS length_new,
  editor_hash,
  regexp_extract(_metadata.file_path, 'live/(.*)$', 1) AS source_file,
  current_timestamp() AS ingested_at
FROM STREAM read_files(
  '{live}/',
  format => 'json',
  schema => 'meta STRUCT<id STRING, dt STRING, stream STRING, domain STRING, uri STRING>,
    wiki STRING, database STRING, type STRING, namespace BIGINT, page_namespace BIGINT,
    page_id BIGINT, title STRING, page_title STRING, rev_id BIGINT, bot BOOLEAN,
    page_is_redirect BOOLEAN, rev_len BIGINT, length_new BIGINT, editor_hash STRING'
);
"""


def _comment(table: str) -> str:
    return datasets()[table]["description"].replace("'", "")


def render_pipeline() -> str:
    """The pipeline SQL: Databricks bronze + slice inputs + the core SQL as materialized views."""
    ds = datasets()
    parts = [
        "-- GENERATED by `babel cloud render` from src/babel_lag/rollup/sql (do not edit).",
        "-- Owner: babel-lag. Domain: knowledge-spread. No personal data (sanitized upstream).",
        BRONZE.format(
            comment=ds["bronze_live_events"]["description"].replace("'", ""), live=LIVE_VOL
        ),  # fmt: skip
    ]
    for t in SLICE_TABLES:
        parts.append(
            f"CREATE OR REFRESH MATERIALIZED VIEW {t}\nCOMMENT '{_comment(t)}'\n"
            f"TBLPROPERTIES ('quality' = 'silver', 'contains_pii' = 'false')\n"
            f"AS SELECT * FROM read_files('{SLICE_VOL}/{t}/', format => 'parquet');\n"
        )
    for t in ALL_TABLES:  # the backfill's all-language gold (ADR-013)
        parts.append(
            f"CREATE OR REFRESH MATERIALIZED VIEW {t}\nCOMMENT '{_comment(t)}'\n"
            f"TBLPROPERTIES ('quality' = 'gold', 'contains_pii' = 'false')\n"
            f"AS SELECT * FROM read_files('{SLICE_VOL}/{t}/', format => 'parquet');\n"
        )
    for table, path in engine.steps():
        if table in SLICE_TABLES:
            continue
        layer = table.split("_", 1)[0]
        body = engine.render(path.read_text("utf-8"), "spark")
        parts.append(
            f"CREATE OR REFRESH MATERIALIZED VIEW {table}\n"
            f"COMMENT '{ds[table]['description'].replace(chr(39), '')}'\n"
            f"TBLPROPERTIES ('quality' = '{layer}', 'contains_pii' = 'false')\nAS\n{body};\n"
        )
    return "\n".join(parts)


def _uploaded() -> set[str]:
    return set(json.loads(STATE.read_text("utf-8"))) if STATE.exists() else set()


def upload(ws: Any) -> dict[str, int]:
    done = _uploaded()
    root = LANDING / "live"
    from datetime import UTC, datetime

    # only batches inside the bronze retention: older live data is not re-sent (quota, $0)
    edge = (datetime.now(UTC) - delta.BRONZE_RETENTION).strftime("%Y%m%dT%H%M%SZ")
    files = [p for p in sorted(root.rglob("*.ndjson"))
             if p.relative_to(root).as_posix() not in done and p.name[:16] >= edge]  # fmt: skip
    nbytes = 0
    for p in files:
        rel = p.relative_to(root).as_posix()
        ws.put_file(p, f"{LIVE_VOL}/{rel}")
        nbytes += p.stat().st_size
        done.add(rel)
        STATE.parent.mkdir(parents=True, exist_ok=True)
        STATE.write_text(json.dumps(sorted(done)), "utf-8")
    # slice tables: re-uploaded only when their Delta version changed
    for t in SLICE_TABLES:
        if not delta.exists(t):
            continue
        from deltalake import DeltaTable

        ver = f"slice:{t}:{DeltaTable(str(delta.path_of(t))).version()}"
        if ver in done:
            continue
        local = DATA / "staging" / "upload" / f"{t}.parquet"
        local.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(delta.read(t), local, compression="zstd")
        ws.put_file(local, f"{SLICE_VOL}/{t}/part-0.parquet")
        nbytes += local.stat().st_size
        local.unlink()
        done = {d for d in done if not d.startswith(f"slice:{t}:")} | {ver}
        STATE.write_text(json.dumps(sorted(done)), "utf-8")
    # all-language gold from the backfill (reference_set `all`), when the local lake holds it
    if delta.exists("gold_language_lag"):
        refs = set(delta.read("gold_language_lag").column("reference_set").to_pylist())
        for t in ALL_TABLES if refs == {"all"} else ():
            src = t.removesuffix("_all")
            from deltalake import DeltaTable

            ver = f"all:{t}:{DeltaTable(str(delta.path_of(src))).version()}"
            if ver in done:
                continue
            local = DATA / "staging" / "upload" / f"{t}.parquet"
            local.parent.mkdir(parents=True, exist_ok=True)
            pq.write_table(delta.read(src), local, compression="zstd")
            ws.put_file(local, f"{SLICE_VOL}/{t}/part-0.parquet")
            nbytes += local.stat().st_size
            local.unlink()
            done = {d for d in done if not d.startswith(f"all:{t}:")} | {ver}
            STATE.write_text(json.dumps(sorted(done)), "utf-8")
    return {"files": len(files), "bytes": nbytes}


def reference_set() -> str:
    """`all` when the local lake holds the backfill's gold, else `slice20`."""
    if delta.exists("gold_language_lag"):
        refs = set(delta.read("gold_language_lag").column("reference_set").to_pylist())
        if refs == {"all"}:
            return "all"
    return "slice20"


def pipeline_tables() -> list[str]:
    """Tables the Lakeflow pipeline defines (silver_page_revisions stays local: only the compact
    page creations are uploaded)."""
    core = [t for t, _ in engine.steps() if t not in SLICE_TABLES]
    return ["bronze_live_events", *SLICE_TABLES, *ALL_TABLES, *core]


def tag_and_comment(ws: Any, warehouse: str) -> dict[str, int]:
    """UC table tags, column comments and the hash column's tag from config/datasets.yml
    (brief section 5b). Lakeflow tables are a streaming table (bronze) and materialized views."""
    tables = columns = 0
    for name in pipeline_tables():
        d = datasets()[name]
        kind = "STREAMING TABLE" if name.startswith("bronze") else "MATERIALIZED VIEW"
        fq = f"workspace.{SCHEMA}.{name}"
        tags = (f"'layer' = '{d['layer']}', 'domain' = '{d['domain']}', 'owner' = '{d['owner']}', "
                f"'classification' = '{d['classification']}', "
                f"'freshness_sla' = '{d['freshness_sla']}'")  # fmt: skip
        try:
            ws.sql(f"ALTER {kind} {fq} SET TAGS ({tags})", warehouse)
            for col, text in (d.get("columns") or {}).items():
                safe = text.replace("'", "")
                ws.sql(f"ALTER {kind} {fq} ALTER COLUMN {col} COMMENT '{safe}'", warehouse)
                columns += 1
                if col == "editor_hash":
                    ws.sql(f"ALTER {kind} {fq} ALTER COLUMN {col} SET TAGS "
                           "('classification' = 'pseudonymous-hash')", warehouse)  # fmt: skip
            tables += 1
        except Exception as exc:  # noqa: BLE001 - a table the pipeline has not built yet
            print(f"tagging {fq} skipped: {str(exc)[:160]}")
    return {"tables": tables, "columns": columns}


def sync_and_run(full_refresh: bool = False) -> dict[str, Any]:
    from babel_lag.cloud.databricks import Workspace

    ws = Workspace.from_env()
    with Stage("databricks_upload", "databricks", __version__, "ingest_bronze_live") as st:
        ws.ensure_schema("babel_landing", "Landing volumes for sanitized batches and slice tables.")
        ws.ensure_schema(SCHEMA, "Babel Lag lakehouse: bronze, silver and gold (Lakeflow).")
        ws.ensure_schema("babel_marts", "Babel Lag dbt marts (dbt-databricks).")
        ws.ensure_volume("babel_landing", "live", "Sanitized EventStreams micro-batches.")
        ws.ensure_volume("babel_landing", "slice", "Compact slice tables from the dumps.")
        res = upload(ws)
        st.records_out, st.bytes_out = res["files"], res["bytes"]
    SQL_FILE.write_text(render_pipeline(), "utf-8")
    with Stage("lakeflow", "databricks", "lakeflow-serverless", "rollup_gold_live_activity") as st:
        # the asset bundle owns the pipeline (CI deploy); create it here only if it is missing
        found = ws.api("GET", "/api/2.0/pipelines", params={"filter": f"name LIKE '{PIPELINE}'"})
        statuses = (found or {}).get("statuses") or []
        pid = (str(statuses[0]["pipeline_id"]) if statuses
               else ws.upsert_pipeline(PIPELINE, SCHEMA, SQL_FILE, WS_PATH))  # fmt: skip
        st.detail["deployed_by"] = "bundle" if statuses else "babel cloud run"
        out = ws.run_pipeline(pid, full_refresh=full_refresh)
        st.detail.update(out, pipeline_id=pid)
        if out["state"] != "COMPLETED":
            raise RuntimeError(f"Lakeflow {out['state']}: {out.get('errors')}")
    wh = ws.warehouse_id()
    ws.ensure_running(wh)
    with Stage("uc_metadata", "databricks", "unity-catalog") as st:
        tagged = tag_and_comment(ws, wh)
        st.records_out = tagged["tables"]
        st.detail.update(tagged)
    return {"upload": res, "pipeline": out}


def write_sql() -> Path:
    SQL_FILE.write_text(render_pipeline(), "utf-8")
    return SQL_FILE


def uc_lineage(table: str = "workspace.babel_marts.mart_language_index", depth: int = 8) -> dict:
    """Walk Unity Catalog table lineage upstream from a mart (lineage-tracking API) and save it
    as evidence: the chain should reach the landing volume (live) and the slice volume."""
    from babel_lag.cloud.databricks import Workspace

    ws = Workspace.from_env()
    seen: dict[str, list[str]] = {}
    frontier = [table]
    with Stage("uc_lineage", "databricks", "unity-catalog") as st:
        for _ in range(depth):
            nxt = []
            for t in frontier:
                if t in seen:
                    continue
                res = (
                    ws.api(
                        "GET",
                        "/api/2.0/lineage-tracking/table-lineage",
                        json={"table_name": t, "include_entity_lineage": True},
                    )
                    or {}
                )
                ups = []
                for u in res.get("upstreams") or []:
                    if "tableInfo" in u:
                        i = u["tableInfo"]
                        ups.append(f"{i['catalog_name']}.{i['schema_name']}.{i['name']}")
                    elif "fileInfo" in u:
                        ups.append("file:" + u["fileInfo"].get("path", "?"))
                    elif u.get("pipelineInfos"):  # Auto Loader streams record no file edge
                        ups += [f"pipeline:{p['pipeline_id']}" for p in u["pipelineInfos"]]
                seen[t] = ups
                nxt += [x for x in ups if ":" not in x.split(".", 1)[0]]
            frontier = nxt
            if not frontier:
                break
        st.records_out = len(seen)
        st.detail.update(tables=len(seen))
    out = DATA / "evidence" / f"uc_lineage_{table.rsplit('.', 1)[-1]}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(seen, indent=1), "utf-8")
    return seen
